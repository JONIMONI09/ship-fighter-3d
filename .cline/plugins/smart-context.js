// smart-context.js — Cline CLI plugin (AgentPlugin, ESM) — v2 "smart-compactor".
//
// Auto-discovered by the Cline CLI from <project>/.cline/plugins/ (docs:
// docs.cline.bot -> Customization -> Plugins). Files must be .ts/.js and
// export an AgentPlugin (default or named export).
//
// Capabilities: hooks only. Prompt/rules injection is NOT a plugin job —
// that is what .clinerules/ (always active) and .cline/skills/ (on demand)
// are for. This plugin provides:
//   1. Policy guard: blocks commands that would kill the agent's own
//      runtime ("taskkill /F /IM node.exe" — docs/LESSONS.md tool safety).
//   2. Token/cost report after every run (token discipline).
//   3. smart-compactor (v2): traces EVERY tool call — success AND failure,
//      nothing skipped — to .cline/plugins/compactor-trace.jsonl and writes
//      .cline/plugins/compactor-summary.md afterRun, so a compacted session
//      resumes from facts instead of replaying the whole chat (token saving).
//
// Note on output: plugin console lines are NOT printed to the CLI stdout
// (verified 2026-09-10, CLI 3.0.61) — check ~/.cline/data/logs/cline.log or
// cline config -> Plugins tab instead. Hook firings were proven via a
// temporary file trace (see tools/plugin-selftest.mjs + session docs).

const BLOCK_PATTERNS = [
  {
    test: /taskkill[\s\S]*\/im\s+node\.exe/i,
    reason:
      "Blocked 'taskkill /IM node.exe': it would kill Cline's own runtime. Kill spawned child processes by PID only.",
  },
  {
    test: /taskkill[\s\S]*\/im\s+cline/i,
    reason: "Blocked: do not kill the Cline CLI process itself.",
  },
];

// --- smart-compactor (v2): trace EVERY tool call, skip nothing ------------
// Writes append-only artifacts under .cline/plugins/ (plugin console output
// does NOT reach CLI stdout, so files are the only reliable channel):
//   compactor-trace.jsonl — one line per tool call (ok:false = failed)
//   compactor-summary.md  — rewritten afterRun with stats for the next session
// Artifacts are size-capped (trace rotates at 512 KB, keeps newest half).

import { appendFileSync, existsSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const TRACE_MAX = 512 * 1024;
const DIGEST_MAX = 220;

function compFile(ctx, name) {
  const cwd = ctx?.cwd ?? process.cwd();
  return join(cwd, ".cline", "plugins", name);
}

function digest(v) {
  if (v == null) return "";
  let s;
  try {
    s = typeof v === "string" ? v : JSON.stringify(v);
  } catch {
    s = String(v);
  }
  return s.length > DIGEST_MAX ? s.slice(0, DIGEST_MAX) + "…" : s;
}

function rotateTrace(p) {
  try {
    if (existsSync(p) && statSync(p).size > TRACE_MAX) {
      const lines = readFileSync(p, "utf8").trim().split("\n");
      writeFileSync(p, lines.slice(Math.floor(lines.length / 2)).join("\n") + "\n");
    }
  } catch {
    /* housekeeping must never break a run */
  }
}

function trace(ctx, rec) {
  try {
    const p = compFile(ctx, "compactor-trace.jsonl");
    appendFileSync(p, JSON.stringify(rec) + "\n");
    rotateTrace(p);
  } catch {
    /* non-fatal */
  }
}

function writeSummary(ctx) {
  try {
    const p = compFile(ctx, "compactor-trace.jsonl");
    const lines = existsSync(p)
      ? readFileSync(p, "utf8").trim().split("\n").filter(Boolean)
      : [];
    let tools = 0,
      fails = 0;
    const byName = {};
    for (const l of lines) {
      let o;
      try {
        o = JSON.parse(l);
      } catch {
        continue;
      }
      if (o.ev !== "tool") continue;
      tools++;
      if (o.ok === false) fails++;
      byName[o.name] = (byName[o.name] || 0) + 1;
    }
    const top =
      Object.entries(byName)
        .sort((a, b) => b[1] - a[1])
        .slice(0, 5)
        .map(([n, c]) => `${n}(${c})`)
        .join(", ") || "none";
    const out = [
      "# Session compaction summary (auto-generated by smart-context v2)",
      `Run ended: ${new Date().toISOString()}`,
      `Tool calls traced: ${tools} (failed: ${fails}) — nothing skipped`,
      `Top tools: ${top}`,
      "Full per-call trace: .cline/plugins/compactor-trace.jsonl",
    ].join("\n");
    writeFileSync(compFile(ctx, "compactor-summary.md"), out);
  } catch {
    /* non-fatal */
  }
}
// --------------------------------------------------------------------------

const plugin = {
  name: "smart-context-agent",
  manifest: {
    capabilities: ["hooks"],
  },

  hooks: {
    beforeRun(ctx) {
      console.log("[smart-context] run started");
      trace(ctx, { t: Date.now(), ev: "run:start" });
      return undefined;
    },

    beforeTool({ toolCall, input, cwd }) {
      const toolName = toolCall?.toolName ?? "unknown";
      const ctxLike = { cwd };
      console.log(`[smart-context] -> ${toolName}`);

      if (
        toolName === "run_commands" &&
        input &&
        Array.isArray(input.commands)
      ) {
        for (const cmd of input.commands) {
          if (typeof cmd !== "string") continue;
          for (const rule of BLOCK_PATTERNS) {
            if (rule.test.test(cmd)) {
              trace(ctxLike, {
                t: Date.now(),
                ev: "tool",
                name: toolName,
                ok: false,
                digest: "BLOCKED: " + rule.reason,
              });
              return { stop: true, reason: rule.reason };
            }
          }
        }
      }
      return undefined;
    },

    afterTool(ctx) {
      const toolName = ctx?.toolCall?.toolName ?? "unknown";
      console.log(`[smart-context] <- ${toolName}`);
      trace(ctx, {
        t: Date.now(),
        ev: "tool",
        name: toolName,
        ok: ctx?.error ? false : true,
        digest: digest(ctx?.error ?? ctx?.result ?? ctx?.output),
      });
      return undefined;
    },

    afterRun(ctx) {
      const result = ctx?.result;
      const usage = result?.usage;
      writeSummary(ctx);
      if (usage) {
        const cost =
          usage.totalCost != null
            ? `, cost: ${
                typeof usage.totalCost === "number"
                  ? usage.totalCost.toFixed(6)
                  : usage.totalCost
              }`
            : "";
        console.log(
          `[smart-context] run done — status: ${result?.status}, tokens in: ${usage.inputTokens}, out: ${usage.outputTokens}${cost}`,
        );
      } else {
        console.log(`[smart-context] run done — status: ${result?.status}`);
      }
      return undefined;
    },
  },
};
export default plugin;
