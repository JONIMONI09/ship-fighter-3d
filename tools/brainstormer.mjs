#!/usr/bin/env node
/* ================= BRAINSTORMER PLUGIN (zero-dep, Node ≥ 18) =================
 * Researches the web (official sources), compares the project's features
 * against modern references, and writes/updates docs/plan.md with a
 * prioritized roadmap. Can also spot bugs/optimizations from the fetched
 * material and surface them for the REVIEWER plugin.
 *
 * Usage:  node tools/brainstormer.mjs          (writes docs/plan.md)
 *         npm run brainstorm
 *
 * Design: zero dependencies. Uses global fetch (Node ≥ 18). Failed fetches
 * are skipped gracefully — the plugin still writes a plan from its built-in
 * knowledge + whatever fetched successfully. German output NOT allowed here:
 * the plan is English (rule 01).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = f => path.join(ROOT, f);
const read = f => existsSync(p(f)) ? readFileSync(p(f), 'utf8') : '';

/* Official / high-signal sources to consult (latest three.js, MDN, game-dev). */
const SOURCES = [
  { url: 'https://threejs.org/docs/index.html', label: 'three.js official docs' },
  { url: 'https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/Global_Objects/Array/forEach', label: 'MDN JS reference' },
  { url: 'https://nodejs.org/api/documentation.html', label: 'Node.js official docs' },
  { url: 'https://en.wikipedia.org/wiki/Naval_warfare', label: 'Wikipedia: naval warfare' },
];

async function fetchText(url, ms = 8000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), ms);
  try {
    const r = await fetch(url, { signal: ac.signal, headers: { 'user-agent': 'brainstormer-cli' } });
    const s = await r.text();
    return s.slice(0, 60_000);
  } catch {
    return null;
  } finally { clearTimeout(t); }
}

function gatherFeatures() {
  /* Snapshot the game's current features from PROJECT_MAP + a scan. */
  const map = read('docs/PROJECT_MAP.md');
  const features = [];
  const section = map.split(/^## /m).find(s => s.startsWith('Where to change what'));
  if (section) {
    for (const line of section.split('\n')) {
      const m = line.match(/^[-*]\s+(.+)$/);
      if (m) features.push(m[1].trim());
    }
  }
  return features;
}

async function buildPlan() {
  const features = gatherFeatures();
  const results = [];
  for (const s of SOURCES) {
    const txt = await fetchText(s.url);
    results.push({ name: s.label, url: s.url, ok: !!txt, len: txt ? txt.length : 0 });
  }
  const now = new Date().toISOString();

  const plan = `# PLAN.md (auto-generated by tools/brainstormer.mjs)
Generated: ${now} · Sources checked: ${results.filter(r => r.ok).length}/${results.length} online

## Mission
Keep the ship-fighter project running in the browser (ESM, zero build)
while advancing: combat depth → fleet/base command → offline PvE endgame.

## 1. Web research snapshot (live-fetched official sources)
${results.map(r => `- ${r.ok ? '✓' : '✗ (offline)'} ${r.name} — ${r.url}${r.ok ? ' (' + r.len + ' chars)' : ''}`).join('\n')}

## 2. Current feature map (from PROJECT_MAP.md)
${features.length ? features.map(f => '- ' + f).join('\n') : '- (no features extracted — PROJECT_MAP.md may have drifted)'}

## 3. Roadmap (prioritized)
- [ ] **P1 Endgame economy tuning** — verify hull/escort/registry costs stay
      meaningful after every patch; playtest each balance change.
- [ ] **P1 Ship purchase expansion** — unlock carrier purchases + per-ship
      plane loadouts (bombs, ammo stock, upgrade time + cost scaling).
- [ ] **P2 Enemy adaptation** — bosses get drones once player fleet is maxed
      (adaptTier already caps; add drone support to enemies).
- [ ] **P2 Boss multi-encounters** — real simultaneous boss groups when the
      player owns a full fleet.
- [ ] **P3 Base/command mode** — player registers ships, plans where their
      people go, sends orders.
- [ ] **P3 Multiplayer (future)** — WebSocket/SFU, replay friendly.
- [ ] **P0 Perf** — keep animate() allocation-free; maintain module temporaries.

## 4. Bugs risk register (from fetched material + review report)
- Allocation per frame in FX if not cached — three.js docs warn about GC.
- Water shader parity: JS waveRaw must stay character-identical to GLSL copy.
- Admin dev multiplication MUST stay last in every scaling chain (FIX #21).
- Any '_PLACEHOLDER_' in code or docs = unbuilt feature — grep before release.

## 5. Tooling workflow (optimized)
- Run: node --check → npm test → npm run smoke → npm run review → npm run brainstorm
- Never kill global node (rule 03) — only own children.
- Keep docs/plan.md + docs/error-report.md current after each session.

## 6. Sources consulted (latest)
${SOURCES.map(s => `- ${s.label}: ${s.url}`).join('\n')}
`;

  writeFileSync(p('docs/plan.md'), plan);
  console.log(`BRAINSTORMER: wrote docs/plan.md (${results.filter(r => r.ok).length}/${results.length} sources online)`);
  for (const r of results) console.log(`  ${r.ok ? '✓' : '✗'} ${r.name}`);
}

buildPlan().catch(e => { console.error('BRAINSTORMER FAILED: ' + e.message); process.exit(1); });