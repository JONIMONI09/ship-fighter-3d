#!/usr/bin/env node
/* ================= REVIEWER PLUGIN (zero-dep, Node ≥ 18) =================
 * Compliance + quality reviewer for the CLI workflow.
 *   1. reads the ACTUAL rules from .clinerules/*.md
 *   2. scans code for what was DONE (FIX: markers, core exports, docs)
 *      and what is MISSING / drift
 *   3. runs lightweight static gates itself (syntax + test count)
 *   4. appends findings to docs/error-report.md WITH solution paths
 * Verdict line: "REVIEWER: PASS|FAIL|ISSUES" — printed last.
 * Usage: node tools/reviewer.mjs  (writes docs/review-report.md)
 *        npm run review
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = f => path.join(ROOT, f);
const read = f => existsSync(p(f)) ? readFileSync(p(f), 'utf8') : '';

function countFixes(file) {
  const s = read(file);
  const markers = (s.match(/FIX:/g) || []).length;
  const nums = [...s.matchAll(/FIX:?\s*#(\d+)/g)].map(m => Number(m[1]));
  const uniq = [...new Set(nums)].sort((a, b) => a - b);
  return { markers, numbered: uniq.length, max: uniq.length ? uniq[uniq.length - 1] : 0 };
}

function extractRules() {
  const out = [];
  for (const r of readdirSync(p('.clinerules'))) {
    if (!r.endsWith('.md')) continue;
    const s = read('.clinerules/' + r);
    out.push(`## ${r}`);
    for (const line of s.split('\n')) {
      const t = line.trim();
      if (!t || t.startsWith('#') || t.startsWith('*') || t.startsWith('-')) continue;
      out.push('- ' + t);
    }
  }
  return out.join('\n');
}

function checkKnowns() {
  const out = [];
  const js = read('js/game.js');
  const core = read('js/core.js');
  const tests = read('tests/core.test.js');
  const exports = [...core.matchAll(/export (?:function|const) (\w+)/g)].map(m => m[1]);
  for (const ex of exports) {
    if (!tests.includes(ex))
      out.push(`⚠ EXPORT '${ex}' not in tests/core.test.js import — add it in the SAME edit (LESSONS.md rule: session-3g import trap).`);
  }
  const fx = countFixes('js/game.js');
  const rulesTxt = read('.clinerules/01-coding-standards.md');
  const markerClaim = rulesTxt.match(/(\d+) FIX: markers/);
  const numClaim = rulesTxt.match(/(\d+) numbered/);
  if (markerClaim && Number(markerClaim[1]) !== fx.markers)
    out.push(`⚠ .clinerules claims ${markerClaim[1]} markers but code has ${fx.markers} — drift.`);
  if (numClaim && Number(numClaim[1]) !== fx.numbered)
    out.push(`⚠ .clinerules claims ${numClaim[1]} numbered fixes but code has ${fx.numbered} — drift.`);
  for (const d of ['docs/LESSONS.md', 'docs/PROJECT_MAP.md', 'docs/plan.md', 'docs/error-report.md', 'README.md'])
    if (!existsSync(p(d))) out.push(`⚠ MISSING DOC: ${d}.`);
  if (/import .*three|document\.|window\.|THREE\./.test(core))
    out.push('⚠ core.js lost purity (three/DOM found) — must stay pure for Node tests.');
  for (const d of ['docs/LESSONS.md', 'docs/PROJECT_MAP.md', 'docs/plan.md']) {
    const s = read(d);
    for (const m of [...s.matchAll(/\b(der|die|das|und|ist|nicht|mit|für|von|auf)\b/gi)].slice(0, 3))
      out.push(`⚠ German word "${m[1]}" in ${d} — docs must be English (rule 01).`);
  }
  return out;
}

function runGates() {
  const g = [];
  for (const f of ['js/core.js', 'js/game.js', 'js/main.js', 'tools/smoke.mjs', 'server.mjs']) {
    const ok = spawnSync('node', ['--check', p(f)]).status === 0;
    g.push(`${ok ? 'PASS' : 'FAIL'}  node --check ${f}`);
  }
  const t2 = spawnSync('node', ['--test', 'tests/core.test.js'], { cwd: p('') });
  const out = t2.stdout ? t2.stdout.toString() : '';
  const pass = (out.match(/ℹ pass (\d+)/) || [])[1];
  const fail = (out.match(/ℹ fail (\d+)/) || [])[1];
  g.push(`${Number(fail) > 0 ? 'FAIL' : 'PASS'}  node --test: ${pass || '?'} pass / ${fail || '?'} fail`);
  return g;
}

const known = checkKnowns();
const gates = runGates();
const fx = countFixes('js/game.js');

const report = `# REVIEW REPORT (auto-generated by tools/reviewer.mjs)
Generated: ${new Date().toISOString()}

## Verdict
**REVIEWER: ${known.length === 0 ? 'PASS' : 'ISSUES' }** — ${known.length} findings.

## 1. Rules in force (read from .clinerules/)
${extractRules()}

## 2. Evidence from code
- FIX: markers ${fx.markers} · numbered refs ${fx.numbered} (max #${fx.max})
- core.js pure: ${/import .*three|document\.|window\.|THREE\./.test(read('js/core.js')) ? 'NO ⚠' : 'YES'}
- Docs: LESSONS.md ${existsSync(p('docs/LESSONS.md')) ? '✓' : '✗'} · PROJECT_MAP.md ${existsSync(p('docs/PROJECT_MAP.md')) ? '✓' : '✗'} · plan.md ${existsSync(p('docs/plan.md')) ? '✓' : '✗'} · error-report.md ${existsSync(p('docs/error-report.md')) ? '✓' : '✗'}

## 3. Findings (missing / drift / optimization)
${known.length ? known.map(k => '- ' + k).join('\n') : '- none detected by static rules.'}

## 4. Suggested optimizations
- Run a full playtest after every economy/UX change (smoke only catches boots).
- Keep admin dev-sliders LAST in every scaling chain (FIX #21 invariant).
- No allocations in the animate loop — reuse module temporaries.
- Add an automated bot-wave replay test when multiplayer is planned.

## 5. Error report appendix
See docs/error-report.md — the living list of errors each with a solution path.
`;

if (!existsSync(p('docs'))) mkdirSync(p('docs'), { recursive: true });
try {
  writeFileSync(p('docs/review-report.md'), report);
  console.log('report → docs/review-report.md');
} catch (e) {
  /* Read-only shells (sandboxed CI, restricted workspaces) must still get
     the verdict. Printing the report is the fallback, not a crash. */
  console.log('report could not be written (' + (e && e.code) + ') — printing instead:');
  console.log(report);
}

console.log(`REVIEWER: ${known.length ? 'ISSUES' : 'PASS'} — ${known.length} findings`);
for (const k of known) console.log('  ' + k);
for (const g of gates) console.log('  ' + g);